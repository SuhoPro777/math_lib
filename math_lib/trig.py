import math

def s(x): return math.sin(x)
def c(x): return math.cos(x)
def t(x): return math.tan(x)
def is_(x): return math.asin(x)
def ic(x): return math.acos(x)
def it(x): return math.atan(x)
def rad(x): return math.radians(x)
def deg(x): return math.degrees(x)
def hyp(a, b): return math.hypot(a, b)
